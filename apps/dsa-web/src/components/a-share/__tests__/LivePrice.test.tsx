import { act,cleanup,fireEvent,render,screen } from '@testing-library/react';
import { afterEach,beforeEach,expect,it,vi } from 'vitest';
import StockDetail from '../StockDetail';
import { aShareMarketApi } from '../../../api/aShareMarket';
import { historyApi } from '../../../api/history';
import type { LivePriceResult } from '../../../types/aShareMarket';
import { liveFixture,unavailableLive } from './liveFixture';
import { outlookFixture,outlookHistory } from './outlookFixture';
vi.mock('../../../api/aShareMarket',()=>({aShareMarketApi:{stock:vi.fn(),history:vi.fn(),scenarios:vi.fn(),outlook:vi.fn(),live:vi.fn(),refreshPrice:vi.fn(),integrated:vi.fn(),prepareResearch:vi.fn(),generateIntegrated:vi.fn()}}));
vi.mock('../../../api/history',()=>({historyApi:{getList:vi.fn(),getDetail:vi.fn()}}));
beforeEach(()=>{
  vi.resetAllMocks();vi.mocked(aShareMarketApi.integrated).mockImplementation(async code=>({code,status:"missing",bundle:null,report:null,demo:false,progress:null,task:null,message:"尚无综合研究"}));vi.useFakeTimers();vi.setSystemTime(new Date('2026-10-14T06:00:00Z'));
  vi.mocked(aShareMarketApi.stock).mockImplementation(async code=>({code,name:code,industries:[],concepts:[],source:'tushare/daily',quote:{price:25,source:'tushare/daily',fetched_at:'2026-10-09T15:00:00+08:00'}}));
  vi.mocked(aShareMarketApi.history).mockImplementation(async(code,_start,_end,adjust)=>outlookHistory(adjust,code));
  vi.mocked(aShareMarketApi.scenarios).mockResolvedValue({status:'insufficient',trade_levels:null,forecasts:[]});
  vi.mocked(aShareMarketApi.outlook).mockImplementation(async code=>outlookFixture(code));
  vi.mocked(aShareMarketApi.live).mockImplementation(async code=>unavailableLive(code));
  vi.mocked(aShareMarketApi.refreshPrice).mockImplementation(async code=>liveFixture(code));
  vi.mocked(historyApi.getList).mockResolvedValue({items:[],total:0,page:1,limit:1});
});
afterEach(()=>{cleanup();vi.useRealTimers();});
it('reads live cache on entry and posts only on click, polls pending every4s, then reloads stock/history/outlook without AI',async()=>{
  const pending={...unavailableLive(),state:'pending' as const,message:'正在刷新最新行情'};
  vi.mocked(aShareMarketApi.live).mockResolvedValueOnce(unavailableLive()).mockResolvedValueOnce(pending).mockResolvedValueOnce(liveFixture());
  vi.mocked(aShareMarketApi.refreshPrice).mockResolvedValue(pending);
  const research=vi.fn();const {container}=render(<StockDetail code="600000" onResearch={research} onWatchlist={()=>{}}/>);
  await act(async()=>{await vi.advanceTimersByTimeAsync(0);});
  expect(aShareMarketApi.refreshPrice).not.toHaveBeenCalled();
  fireEvent.click(screen.getByRole('button',{name:'刷新最新行情'}));
  await act(async()=>{await vi.advanceTimersByTimeAsync(0);});
  expect(screen.getByRole('button',{name:'刷新最新行情'})).toBeDisabled();
  await act(async()=>{await vi.advanceTimersByTimeAsync(3999);});
  expect(aShareMarketApi.live).toHaveBeenCalledTimes(1);
  await act(async()=>{await vi.advanceTimersByTimeAsync(1);});
  expect(aShareMarketApi.live).toHaveBeenCalledTimes(2);
  await act(async()=>{await vi.advanceTimersByTimeAsync(4000);});
  expect(aShareMarketApi.refreshPrice).toHaveBeenCalledTimes(1);expect(aShareMarketApi.live).toHaveBeenCalledTimes(3);
  expect(screen.getByRole('button',{name:'刷新最新行情'})).toBeEnabled();
  expect(container.querySelector('.am-quote')).toHaveTextContent('¥27.50');
  expect(container.querySelector('[data-live-date="2026-10-14"]')).toBeInTheDocument();
  expect(screen.getAllByText(/未完成/).length).toBeGreaterThan(0);
  expect(aShareMarketApi.history).toHaveBeenCalledTimes(4);
  expect(vi.mocked(aShareMarketApi.history).mock.calls.every(call=>call[5]===false)).toBe(true);
  expect(aShareMarketApi.outlook).toHaveBeenCalledTimes(2);
  expect(aShareMarketApi.outlook).toHaveBeenLastCalledWith('600000',2,expect.any(AbortSignal),false);
  expect(aShareMarketApi.stock).toHaveBeenCalledTimes(2);expect(aShareMarketApi.scenarios).toHaveBeenCalledTimes(1);expect(research).not.toHaveBeenCalled();
});
it('keeps already obtained quote and temporary bar after a refresh error',async()=>{
  vi.mocked(aShareMarketApi.live).mockResolvedValue(liveFixture());
  const {container}=render(<StockDetail code="600000" onResearch={()=>{}} onWatchlist={()=>{}}/>);
  await act(async()=>{await vi.advanceTimersByTimeAsync(0);});
  vi.mocked(aShareMarketApi.refreshPrice).mockRejectedValue(new Error('最新行情连接中断'));
  fireEvent.click(screen.getByRole('button',{name:'刷新最新行情'}));
  await act(async()=>{await vi.advanceTimersByTimeAsync(0);});
  expect(screen.getByRole('alert')).toHaveTextContent('最新行情连接中断');
  expect(container.querySelector('.am-quote')).toHaveTextContent('¥27.50');
  expect(container.querySelector('[data-live-date="2026-10-14"]')).toBeInTheDocument();
  expect(screen.getByRole('button',{name:'刷新最新行情'})).toBeEnabled();
});
it('aborts an old stock refresh and never applies its reply or reloads to another stock',async()=>{
  let resolve!:(value:LivePriceResult)=>void;let signal:AbortSignal|undefined;
  vi.mocked(aShareMarketApi.refreshPrice).mockImplementation((_code,s)=>{signal=s;return new Promise(r=>{resolve=r;});});
  const {container,rerender}=render(<StockDetail code="600000" onResearch={()=>{}} onWatchlist={()=>{}}/>);
  await act(async()=>{await vi.advanceTimersByTimeAsync(0);});
  fireEvent.click(screen.getByRole('button',{name:'刷新最新行情'}));
  rerender(<StockDetail code="600001" onResearch={()=>{}} onWatchlist={()=>{}}/>);
  await act(async()=>{await vi.advanceTimersByTimeAsync(0);});
  expect(signal?.aborted).toBe(true);
  await act(async()=>resolve(liveFixture('600000')));
  expect(container.querySelector('[data-live-date]')).not.toBeInTheDocument();expect(container.querySelector('.am-quote')).toHaveTextContent('¥25.00');
  expect(aShareMarketApi.outlook).toHaveBeenCalledTimes(2);
});
