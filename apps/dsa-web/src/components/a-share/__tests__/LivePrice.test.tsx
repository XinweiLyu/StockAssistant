  const ready={...liveFixture(),provisional:false,history_updated:true,completed_day:'2026-10-14'};
  let completed=false;
  vi.mocked(aShareMarketApi.history).mockImplementation(async(code,_start,_end,adjust)=>{const h=outlookHistory(adjust,code);return completed?{...h,items:[...h.items,ready.bars[adjust]!],actual_end:'2026-10-14'}:h;});
